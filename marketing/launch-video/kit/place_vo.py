"""Places a voice read on a finished film: each row of <dir>/script.txt at its own start time.

  python kit/place_vo.py launch/vo-read launch-vo/vo --dur 33

Reads the takes voice.py chose (<dir>/run.log, <dir>/takes/) and the word stamps in <dir>/timing.js,
puts each row at SLOTS[tag] (optionally sped up a touch so it ends before the next line), and writes
<out>/vo.wav plus <out>/place.js (VOP: each row's start and per-word times) for the film's captions.
"""
import argparse, json, os, re, subprocess
import numpy as np, soundfile as sf

# tag: (start in the film, speed). Starts follow the captions in launch/film.js.
SLOTS = {'hook1': (.30, 1), 'hook2': (2.0, 1), 'meet': (4.4, 1), 'tag': (5.3, 1.05), 'once': (10.2, 1),
         'right': (12.95, 1), 'pick': (14.15, 1), 'done': (16.85, 1), 'saved': (18.35, 1), 'f1': (20.3, 1), 'f2': (21.78, 1),
         'offline': (24.2, 1.08), 'noads': (25.25, 1.12), 'free': (27.42, 1), 'end': (28.3, 1)}
SR = 48000
ap = argparse.ArgumentParser(); ap.add_argument('src'); ap.add_argument('out'); ap.add_argument('--dur', type=float, required=True); a = ap.parse_args()
os.makedirs(a.out, exist_ok=True)
tim = open(os.path.join(a.src, 'timing.js')).read()
lines = json.loads(re.search(r'VO_LINES = (.*);', tim).group(1)); words = json.loads(re.search(r'VO_WORDS = (.*);', tim).group(1))
picked = [int(m) for m in re.findall(r'^row \d+: take (\d+)', open(os.path.join(a.src, 'run.log')).read(), re.M)]
assert len(picked) == len(lines), 'run.log and timing.js disagree'

def load(path, speed):
    cmd = ['ffmpeg', '-v', 'error', '-i', path, '-af', f'atempo={speed},aresample={SR}', '-ac', '1', '-f', 'f32le', '-']
    return np.frombuffer(subprocess.run(cmd, capture_output=True, check=True).stdout, np.float32)

vo = np.zeros(int(a.dur * SR), np.float32); place = {}; prev_end, prev_tag = 0, None
for k, L in enumerate(lines):
    t0, speed = SLOTS[L['tag']]
    x = load(os.path.join(a.src, 'takes', f'{k:02d}-{picked[k]}.wav'), speed)
    end = t0 + len(x) / SR
    assert t0 >= prev_end - 1e-3, f"{L['tag']} starts at {t0:.2f} before {prev_tag} ends at {prev_end:.2f}"
    i = int(t0 * SR); vo[i:i + len(x)] += x[:len(vo) - i]
    ws = [w for w in words if w['line'] == k]
    place[L['tag']] = {'start': round(t0, 3), 'end': round(end, 3), 'text': L['text'],
                       'words': [round(t0 + (w['t'] - L['start']) / speed, 3) for w in ws]}
    print(f"{t0:6.2f}-{end:6.2f}  x{speed:<4}  {L['text']}")
    prev_end, prev_tag = end, L['tag']
vo = vo / max(1e-6, np.abs(vo).max()) * .89
sf.write(os.path.join(a.out, 'vo.wav'), vo, SR, subtype='PCM_16')
with open(os.path.join(a.out, 'place.js'), 'w') as f:
    f.write('// generated by kit/place_vo.py — do not edit by hand\nconst VOP = ' + json.dumps(place) + ';\n')
print('->', os.path.join(a.out, 'vo.wav'))
